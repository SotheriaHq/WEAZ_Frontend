const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const headersPath = path.join(root, 'public', '_headers');
const vercelPath = path.join(root, 'vercel.json');

const appBaseUrl = String(process.env.VITE_APP_URL ?? 'https://weaz.me')
  .trim()
  .replace(/\/+$/, '');

const apiBaseUrl = String(process.env.VITE_API_BASE_URL ?? 'https://api.weaz.me')
  .trim()
  .replace(/\/+$/, '');

const gaMeasurementId = String(process.env.VITE_GA_MEASUREMENT_ID ?? '').trim();

const apiWsBaseUrl = apiBaseUrl.replace(/^https:/, 'wss:').replace(/^http:/, 'ws:');

const buildConnectSrc = () => {
  const sources = new Set([
    "'self'",
    'https://accounts.google.com',
    'https://restcountries.com',
    'https://countriesnow.space',
    'http://localhost:3040',
    'http://127.0.0.1:3040',
    'ws://localhost:3040',
    'ws://127.0.0.1:3040',
    apiBaseUrl,
    apiWsBaseUrl,
    'https://*.amazonaws.com',
    'https://api.paystack.co',
    'https://checkout.paystack.com',
    'https://standard.paystack.co',
    'https://js.paystack.co',
    'https://www.googletagmanager.com',
    'https://www.google-analytics.com',
    'https://region1.google-analytics.com',
  ]);
  return Array.from(sources).join(' ');
};

const scriptSrc = [
  "'self'",
  'https://accounts.google.com',
  'https://js.paystack.co',
  'https://checkout.paystack.com',
  'https://standard.paystack.co',
  ...(gaMeasurementId ? ['https://www.googletagmanager.com'] : []),
].join(' ');

const csp = [
  "default-src 'self'",
  "base-uri 'self'",
  "object-src 'none'",
  "frame-ancestors 'none'",
  `script-src ${scriptSrc}`,
  "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com",
  "img-src 'self' data: blob: https://*.amazonaws.com https://*.s3.amazonaws.com https://*.cloudfront.net https://res.cloudinary.com https://images.unsplash.com https://lh3.googleusercontent.com https://unavatar.io https://flagcdn.com https://checkout.paystack.com https://standard.paystack.co",
  "font-src 'self' data: https://fonts.gstatic.com",
  `connect-src ${buildConnectSrc()}`,
  'frame-src https://accounts.google.com https://checkout.paystack.com https://standard.paystack.co https://js.paystack.co',
  "form-action 'self' https://checkout.paystack.com https://standard.paystack.co",
  "worker-src 'self' blob:",
  'upgrade-insecure-requests',
].join('; ');

const headersTemplate = `# Generated by scripts/generate-security-headers.cjs — do not hand-edit connect-src API host.
/assets/*
  Cache-Control: public, max-age=31536000, immutable

/
  Cache-Control: no-cache, no-store, must-revalidate
/index.html
  Cache-Control: no-cache, no-store, must-revalidate
# Boot scripts pair with index.html (CSP forbids inline scripts) and contain
# the stale-cache self-heal — they must never be served stale themselves.
/boot/theme-init.js
  Cache-Control: no-cache, no-store, must-revalidate
/boot/boot-splash.js
  Cache-Control: no-cache, no-store, must-revalidate
/boot/*
  Cache-Control: no-cache, no-store, must-revalidate

/*
  Content-Security-Policy: ${csp}
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=()
  X-Content-Type-Options: nosniff
`;

fs.writeFileSync(headersPath, headersTemplate, 'utf8');

const vercelConfig = {
  headers: [
    {
      source: '/',
      headers: [
        { key: 'Cache-Control', value: 'no-cache, no-store, must-revalidate' },
      ],
    },
    {
      source: '/index.html',
      headers: [
        { key: 'Cache-Control', value: 'no-cache, no-store, must-revalidate' },
      ],
    },
    {
      source: '/boot/(.*)',
      headers: [
        { key: 'Cache-Control', value: 'no-cache, no-store, must-revalidate' },
      ],
    },
    {
      source: '/(.*)',
      headers: [
        { key: 'Content-Security-Policy', value: csp },
        { key: 'X-Frame-Options', value: 'DENY' },
        { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' },
        { key: 'Permissions-Policy', value: 'camera=(), microphone=(), geolocation=()' },
        { key: 'X-Content-Type-Options', value: 'nosniff' },
      ],
    },
  ],
};

fs.writeFileSync(vercelPath, `${JSON.stringify(vercelConfig, null, 2)}\n`, 'utf8');

const analyticsBootPath = path.join(root, 'public', 'boot', 'analytics.js');
const analyticsBoot = `// Generated by scripts/generate-security-headers.cjs
(function () {
  var measurementId = ${JSON.stringify(gaMeasurementId)};
  if (!measurementId) return;

  window.dataLayer = window.dataLayer || [];
  window.gtag = window.gtag || function () {
    window.dataLayer.push(arguments);
  };

  var script = document.createElement('script');
  script.async = true;
  script.src = 'https://www.googletagmanager.com/gtag/js?id=' + encodeURIComponent(measurementId);
  document.head.appendChild(script);

  window.gtag('js', new Date());
  window.gtag('config', measurementId, { send_page_view: false });
})();
`;
fs.writeFileSync(analyticsBootPath, analyticsBoot, 'utf8');

console.log(`Generated security headers with API host ${apiBaseUrl} and app URL ${appBaseUrl}`);
