import { createHash } from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Explicit maintenance command; normal builds use the committed artifacts and
// require no Google connection. Keep every original weight and Unicode subset.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const cssUrl = 'https://fonts.googleapis.com/css2?family=Playfair+Display:wght@500;600;700&family=Plus+Jakarta+Sans:wght@400;500;600;700&display=swap';
const headers = { 'User-Agent': 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/155.0.0.0 Safari/537.36' };
const out = path.join(root, 'public', 'fonts', 'wiez-web');
const fetchBytes = async (url) => {
  const response = await fetch(url, { headers, signal: AbortSignal.timeout(30_000) });
  if (!response.ok) throw new Error(`Font download failed (${response.status}): ${url}`);
  return Buffer.from(await response.arrayBuffer());
};
const originalCss = (await fetchBytes(cssUrl)).toString('utf8');
const faces = [...originalCss.matchAll(/\/\* ([^*]+) \*\/\s*(@font-face\s*\{[^}]+\})/g)];
if (faces.length !== 28) throw new Error(`Expected all 28 approved font faces; received ${faces.length}`);
const artifacts = new Map();
const css = [];
await fs.mkdir(out, { recursive: true });
for (const [, subset, face] of faces) {
  const family = /font-family: '([^']+)'/.exec(face)?.[1];
  const source = /src: url\((https:\/\/fonts\.gstatic\.com\/[^)]+\.woff2)\)/.exec(face)?.[1];
  if (!source || !family || !['Playfair Display', 'Plus Jakarta Sans'].includes(family)) throw new Error('Unexpected font source or family');
  if (!artifacts.has(source)) {
    const bytes = await fetchBytes(source);
    if (bytes.toString('ascii', 0, 4) !== 'wOF2') throw new Error('Font response is not WOFF2');
    const sha256 = createHash('sha256').update(bytes).digest('hex');
    const name = `${family.toLowerCase().replaceAll(' ', '-')}-${subset.trim()}-${sha256.slice(0,12)}.woff2`;
    await fs.writeFile(path.join(out, name), bytes);
    artifacts.set(source, { name, sha256, bytes: bytes.length, source });
  }
  css.push(`/* ${subset.trim()} */\n${face.replace(source, `/fonts/wiez-web/${artifacts.get(source).name}`)}`);
}
for (const [name, source] of [
  ['plus-jakarta-sans-OFL.txt', 'https://raw.githubusercontent.com/google/fonts/main/ofl/plusjakartasans/OFL.txt'],
  ['playfair-display-OFL.txt', 'https://raw.githubusercontent.com/google/fonts/main/ofl/playfairdisplay/OFL.txt'],
  ['playfair-display-FONTLOG.txt', 'https://raw.githubusercontent.com/google/fonts/main/ofl/playfairdisplay/FONTLOG.txt'],
]) {
  const license = (await fetchBytes(source)).toString('utf8').replace(/\r\n?/g, '\n').replace(/[ \t]+$/gm, '');
  await fs.writeFile(path.join(out, name), license);
}
const generatedCss = `/* Generated by scripts/vendor-web-fonts.mjs; original licenses are in /fonts/wiez-web. */\n${css.join('\n')}\n`;
await fs.writeFile(path.join(root, 'src', 'styles', 'web-fonts.css'), generatedCss);
await fs.writeFile(path.join(out, 'manifest.json'), JSON.stringify({ stylesheetSource: cssUrl, faces: faces.length, files: [...artifacts.values()] }, null, 2) + '\n');
const bodyFont = [...artifacts.values()].find(file => /^plus-jakarta-sans-latin-[a-f0-9]+\.woff2$/.test(file.name));
if (!bodyFont) throw new Error('Missing primary Latin font');
const indexPath = path.join(root, 'index.html');
const index = await fs.readFile(indexPath, 'utf8');
await fs.writeFile(indexPath, index.replace(/\/fonts\/wiez-web\/plus-jakarta-sans-latin-[a-f0-9]+\.woff2/g, `/fonts/wiez-web/${bodyFont.name}`));
console.log(`Vendored ${artifacts.size} unmodified WOFF2 files for ${faces.length} font faces.`);
